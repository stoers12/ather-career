/** An allowlisted interface preference, independent of Profile and authorization. */
function ownerLocale(): string
{
    $value = $_GET['lang'] ?? ($_COOKIE['ather_owner_locale'] ?? 'ar');
    return $value === 'en' ? 'en' : 'ar';
}

function ownerPersistLocale(string $locale): void
{
    if (PHP_SAPI === 'cli' || headers_sent()) {
        return;
    }
    header('Content-Language: ' . $locale);
    if (in_array($_GET['lang'] ?? null, ['ar', 'en'], true) && ($_COOKIE['ather_owner_locale'] ?? null) !== $locale) {
        setcookie('ather_owner_locale', $locale, [
            'path' => '/', 'secure' => applicationSessionCookieIsSecure(), 'httponly' => true, 'samesite' => 'Lax',
        ]);
    }
}

/** Preserve the current editor/detail state; never accept an external return URL. */
function ownerLanguageUrl(string $locale): string
{
    $path = parse_url((string) ($_SERVER['REQUEST_URI'] ?? '/owner.php'), PHP_URL_PATH);
    if (!in_array($path, ['/owner.php', '/owner_profile.php', '/owner_projects.php', '/owner_experiences.php', '/owner_messages.php', '/owner_publication.php', '/owner_settings.php', '/owner/evidence-hub'], true)
        && (!is_string($path) || preg_match('@^/owner/projects/[1-9][0-9]*/evidence$@D', $path) !== 1)) {
        $path = '/owner.php';
    }
    $query = [];
    foreach (['add', 'edit', 'message', 'slug_saved', 'published', 'unpublished'] as $key) {
        if (isset($_GET[$key]) && is_string($_GET[$key])) {
            $query[$key] = $_GET[$key];
        }
    }
    $query['lang'] = $locale === 'en' ? 'en' : 'ar';
    return $path . '?' . http_build_query($query, '', '&', PHP_QUERY_RFC3986);
}

